#!/usr/bin/env python3
"""Build scripts/seed/demo_seed.sql: the whole demo catalog as one SQL file.

It reads the same files the app's demo loader reads (backend/src/main/resources/demo/catalog.json and
marketplace.json) and writes plain SQL that adds the same rows. Use it to fill a fresh database without
the Admin → Demo data screen:

  python3 scripts/seed/build_demo_seed_sql.py             # regenerate demo_seed.sql
  psql "$DATABASE_URL" -f scripts/seed/demo_seed.sql       # load it, after the app's migrations have run

The file is safe to run twice: every insert checks that the row is not there yet.
Everything it adds uses a "demo-" slug or a "@demo.sodogebeya.et" email, so it can be removed the same way
as the loader's data. Photos are served from /demo/<slug>.jpg by the frontend (frontend/public/demo).
"""

import json
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEMO = ROOT / "backend/src/main/resources/demo"
OUT = ROOT / "scripts/seed/demo_seed.sql"
PREFIX = "demo-"
DOMAIN = "demo.sodogebeya.et"
NAMESPACE = uuid.UUID("6f1c2a0e-3b8e-4a53-9d6b-5e0c1f9a7b21")  # fixed, so user ids are the same on every run


def lit(value):
    """SQL literal. Text uses dollar quoting, so apostrophes and quotes need no escaping."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    text = str(value)
    tag = "$q$"
    while tag in text:
        tag = "$q" + tag[2:]
    return f"{tag}{text}{tag}"


def description(p):
    if p.get("description"):
        return p["description"]
    return {
        "USED": "Used, in good working condition. You can come and check it before buying. Price is a little negotiable.",
        "LIKE_NEW": "Like new, hardly used. Fully checked and cleaned.",
    }.get(p.get("condition", "NEW"),
          "Brand new. Delivery anywhere in Sodo; pay safely online with BillPay.")


def user_id(email):
    return str(uuid.uuid5(NAMESPACE, email))


def user_insert(email, full_name, phone):
    return (f"insert into users (id, email, password_hash, full_name, phone, role, enabled) "
            f"select {lit(user_id(email))}::uuid, {lit(email)}, null, {lit(full_name)}, {lit(phone)}, 'CUSTOMER', true "
            f"where not exists (select 1 from users where email = {lit(email)});")


def build():
    catalog = json.loads((DEMO / "catalog.json").read_text(encoding="utf-8"))
    market = json.loads((DEMO / "marketplace.json").read_text(encoding="utf-8"))
    out = ["-- Demo seed: generated by scripts/seed/build_demo_seed_sql.py. Do not edit by hand.",
           "-- Safe to run twice. Run after the app's migrations, e.g.: psql \"$DATABASE_URL\" -f scripts/seed/demo_seed.sql",
           "BEGIN;", ""]

    out.append("-- 1. Categories (parents first)")
    for c in catalog["categories"]:
        parent = (f"(select id from categories where slug = {lit(c['parent'])})" if c.get("parent") else "NULL")
        out.append(
            "insert into categories (name, slug, parent_id, sort_order, active) "
            f"select {lit(c['name'])}, {lit(c['slug'])}, {parent}, "
            "(select coalesce(max(sort_order), 0) + 1 from categories), true "
            f"where not exists (select 1 from categories where slug = {lit(c['slug'])});")
    out.append("")

    out.append("-- 2. Shops, each with its owner account (no password, so nobody can sign in as them)")
    shop_area = {}
    for sh in catalog["shops"]:
        shop_area[sh["slug"]] = sh["area"]
        owner_email = f"{sh['slug']}@{DOMAIN}"
        out.append(user_insert(owner_email, sh["name"], sh["phone"]))
        out.append(
            "insert into shops (owner_id, kind, name, slug, description, phone, area, address_line, status, "
            "decided_at, decided_by, verified_at) "
            f"select {lit(user_id(owner_email))}::uuid, {lit(sh['kind'])}, {lit(sh['name'])}, {lit(PREFIX + sh['slug'])}, "
            f"{lit(sh['about'])}, {lit(sh['phone'])}, {lit(sh['area'])}, {lit(sh.get('address'))}, 'APPROVED', "
            "now(), 'demo data', now() "
            f"where not exists (select 1 from shops where slug = {lit(PREFIX + sh['slug'])});")
    out.append("")

    out.append("-- 3. Goods listings")
    for p in catalog["products"]:
        specs = json.dumps(p.get("specs", {}), ensure_ascii=False)
        out.append(
            "insert into products (category_id, shop_id, name, slug, description, price, currency, stock, image_url, "
            "featured, active, item_condition, negotiable, area, specs, created_at, updated_at) "
            f"select (select id from categories where slug = {lit(p['category'])}), "
            f"(select id from shops where slug = {lit(PREFIX + p['shop'])}), "
            f"{lit(p['name'])}, {lit(p['slug'])}, {lit(description(p))}, {lit(p['price'])}, 'ETB', "
            f"{int(p.get('stock', 5))}, {lit('/demo/' + p['slug'] + '.jpg')}, {lit(bool(p.get('featured')))}, true, "
            f"{lit(p.get('condition', 'NEW'))}, {lit(bool(p.get('negotiable')))}, {lit(shop_area[p['shop']])}, "
            f"{lit(specs)}::jsonb, now(), now() "
            f"where not exists (select 1 from products where slug = {lit(p['slug'])});")
    out.append("")

    out.append("-- 4. Services (Hire a pro): profile, then its price list")
    for p in market["pros"]:
        email = f"demo-pro-{p['slug']}@{DOMAIN}"
        out.append(user_insert(email, p["display_name"], p["phone"]))
        out.append(
            "insert into pro_profiles (owner_id, display_name, trade, headline, bio, years_experience, areas, phone, "
            "status, decided_at, decided_by, jobs_done, rating_sum, rating_count, created_at, updated_at) "
            f"select {lit(user_id(email))}::uuid, {lit(p['display_name'])}, {lit(p['trade'])}, {lit(p.get('headline'))}, "
            f"{lit(p.get('bio'))}, {p['years']}, {lit(p.get('areas'))}, {lit(p['phone'])}, 'APPROVED', now(), 'demo data', "
            f"{p['jobs_done']}, {p['rating_sum']}, {p['rating_count']}, now(), now() "
            f"where not exists (select 1 from pro_profiles pp join users u on u.id = pp.owner_id where u.email = {lit(email)});")
        for pos, (label, price) in enumerate(p["prices"]):
            out.append(
                "insert into pro_prices (pro_id, label, price_from, position) "
                f"select pp.id, {lit(label)}, {lit(price)}, {pos} from pro_profiles pp join users u on u.id = pp.owner_id "
                f"where u.email = {lit(email)} and not exists (select 1 from pro_prices x where x.pro_id = pp.id and x.label = {lit(label)});")
    out.append("")

    out.append("-- 5. Job posts")
    for j in market["jobs"]:
        employer_email = f"demo-employer-{slug_of(j['employer'])}@{DOMAIN}"
        out.append(user_insert(employer_email, j["employer"], None))
        out.append(
            "insert into job_posts (employer_id, employer_name, title, place, job_type, field, salary_min, salary_max, "
            "salary_note, description, requirements, deadline, status, fee, fee_paid, featured, decided_by, decided_at, "
            "created_at, updated_at) "
            f"select {lit(user_id(employer_email))}::uuid, {lit(j['employer'])}, {lit(j['title'])}, {lit(j['place'])}, "
            f"{lit(j['job_type'])}, {lit(j.get('field'))}, {lit(j.get('salary_min'))}, {lit(j.get('salary_max'))}, "
            f"{lit(j.get('salary_note'))}, {lit(j['description'])}, {lit(j.get('requirements'))}, "
            f"current_date + {int(j.get('deadline_days', 30))}, 'LIVE', 0, true, false, 'demo data', now(), now(), now() "
            f"where not exists (select 1 from job_posts where employer_name = {lit(j['employer'])} and title = {lit(j['title'])});")
    out.append("")

    out.append("-- 6. Talent profiles (public)")
    for t in market["talent"]:
        email = f"demo-talent-{t['slug']}@{DOMAIN}"
        out.append(user_insert(email, t["full_name"], None))
        grad = t.get("graduation_year")
        out.append(
            "insert into talent_profiles (user_id, full_name, status, headline, about, school, field_of_study, "
            "graduation_year, skills, languages, work_types, work_places, public_profile, created_at, updated_at) "
            f"select {lit(user_id(email))}::uuid, {lit(t['full_name'])}, {lit(t['status'])}, {lit(t.get('headline'))}, "
            f"{lit(t.get('about'))}, {lit(t.get('school'))}, {lit(t.get('field_of_study'))}, {lit(grad)}, "
            f"{lit(t.get('skills'))}, {lit(t.get('languages'))}, {lit(t.get('work_types'))}, {lit(t.get('work_places'))}, "
            "true, now(), now() "
            f"where not exists (select 1 from talent_profiles tp join users u on u.id = tp.user_id where u.email = {lit(email)});")
    out.append("")
    out.append("COMMIT;")
    return "\n".join(out) + "\n"


def slug_of(text):
    import re
    return re.sub(r"(^-|-$)", "", re.sub(r"[^a-z0-9]+", "-", text.lower()))


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    sql = build()
    OUT.write_text(sql, encoding="utf-8")
    print(f"wrote {OUT} ({sql.count(chr(10))} lines, {sql.count(';')} statements)")
